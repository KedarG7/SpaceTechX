import { circlePolygon } from "../utils/geo.js";

function incident({
  code,
  name,
  category,
  subCategory,
  state,
  district,
  latitude,
  longitude,
  radiusKm,
  severity,
  reason,
  eventTime,
  activationTime,
  lastUpdate,
  closed,
  stats,
  aoiName,
  copernicusRef,
}) {
  const aoi = circlePolygon(longitude, latitude, radiusKm, 40);
  const areaKm2 = Number((Math.PI * radiusKm * radiusKm).toFixed(1));
  return {
    id: code,
    code,
    name,
    category,
    subCategory,
    countries: ["India"],
    state,
    district,
    centroid: { latitude, longitude },
    severity,
    closed,
    mode: "demo",
    source: "Demo / historical India catalogue (patterned on Copernicus EMS Rapid Mapping products)",
    copernicusRef,
    reason,
    eventTime,
    activationTime,
    lastUpdate,
    n_aois: 1,
    n_products: 1,
    gdacsId: null,
    extentGeoJSON: aoi,
    affectedAreaKm2: areaKm2,
    aois: [
      {
        name: aoiName,
        number: 1,
        extentGeoJSON: aoi,
        products: [
          {
            type: "GRA",
            monitoring: false,
            feasible: true,
            stats,
            layers: [],
          },
        ],
      },
    ],
    impact: {
      buildingsAffected: stats.buildingsAffected,
      buildingsTotal: stats.buildingsTotal,
      roadsAffectedKm: stats.roadsAffectedKm,
      roadsTotalKm: stats.roadsTotalKm,
      populationEstimated: stats.populationEstimated,
      populationAffected: stats.populationAffected,
      landUseAffectedHa: stats.landUseAffectedHa,
    },
    dataConfidence: {
      disaster: "Simulated activation for Indian EOC demonstration. Structure follows Copernicus EMS Rapid Mapping activation/AOI/product statistics.",
      area: "Prototype AOI generated around documented event locality; not an official CEMS footprint.",
      hospitals: "Government of India hospital directory (compiled seed).",
    },
  };
}

